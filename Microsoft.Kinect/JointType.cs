		/// </summary>
		HipCenter,
		/// <summary>
		/// The bottom of the spine.
		/// </summary>
		Spine,
		/// <summary>
		/// The center of the shoulders.
		/// </summary>
		ShoulderCenter,
		/// <summary>
		/// The players head.
		/// </summary>
		Head,
		/// <summary>
		/// The left shoulder.
		/// </summary>
		ShoulderLeft,
		/// <summary>
		/// The left elbow.
		/// </summary>
		ElbowLeft,
		/// <summary>
		/// The left wrist.
		/// </summary>
		WristLeft,
		/// <summary>
		/// The left hand.
		/// </summary>
		HandLeft,
		/// <summary>
		/// The right shoulder.
		/// </summary>
		ShoulderRight,
		/// <summary>
		/// The right elbow.
		/// </summary>
		ElbowRight,
		/// <summary>
		/// The right wrist.
		/// </summary>
		WristRight,
		/// <summary>
		/// The right hand.
		/// </summary>
		HandRight,
		/// <summary>
		/// The left hip.
		/// </summary>
		HipLeft,
		/// <summary>
		/// The left knee.
		/// </summary>
		KneeLeft,
		/// <summary>
		/// The left ankle.
		/// </summary>
		AnkleLeft,
		/// <summary>
		/// The left foot.
		/// </summary>
		FootLeft,
		/// <summary>
		/// The right hip.
		/// </summary>
		HipRight,
		/// <summary>
		/// The right knee.
		/// </summary>
		KneeRight,
		/// <summary>
		/// The right ankle.
		/// </summary>
		AnkleRight,
		/// <summary>
		/// The right foot.
		/// </summary>
		FootRight
	}
}
